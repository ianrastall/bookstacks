"""Check distinct language files against the reviewed 38-play checklist."""
import argparse
import json
from pathlib import Path
from lxml import etree

ROOT = Path(__file__).resolve().parents[1]
NS = {'t': 'http://www.tei-c.org/ns/1.0'}
LANGUAGES = {'eng': 'en', 'fra': 'fr', 'spa': 'es'}


def audit():
    plays = json.loads((ROOT / 'src/data/shakespeare-plays.json').read_text(encoding='utf-8'))
    expected = {p['slug'] for p in plays}
    if len(plays) != 38 or len(expected) != 38:
        raise ValueError('The reviewed checklist must contain 38 distinct plays')
    found = {lang: set() for lang in LANGUAGES}
    for path in sorted((ROOT / 'tei/shakespeare').glob('*.xml')):
        stem = path.stem.removeprefix('shakespeare_')
        slug, lang = stem.rsplit('_', 1)
        if slug not in expected or lang not in found:
            raise ValueError(f'Unreviewed play/language: {path.name}')
        document = etree.parse(str(path))
        language = document.xpath('string(//t:text/@xml:lang)', namespaces=NS)
        if language != LANGUAGES[lang]: raise ValueError(f'Language mismatch: {path.name}')
        acts = document.xpath('//t:div[@type="act"]', namespaces=NS)
        # Some source editions encode the induction as an additional act.
        if len(acts) < 5 or not document.xpath('//t:sp', namespaces=NS):
            raise ValueError(f'Incomplete dramatic structure: {path.name}')
        found[lang].add(slug)
    for lang in ('eng', 'fra'):
        if found[lang] != expected:
            raise ValueError(f'Incomplete {lang} collection: {sorted(expected - found[lang])}')
    rows = ['<!-- Generated by python scripts/audit_shakespeare.py --write. -->',
            '| Play | English | French | Spanish |', '| --- | --- | --- | --- |']
    for play in plays:
        cells = []
        for lang, code in LANGUAGES.items():
            cells.append(f'[Read](https://bookstacks.org/{code}/authors/shakespeare/{play["slug"]})' if play['slug'] in found[lang] else 'Pending')
        rows.append('| ' + ' | '.join([play['title'], *cells]) + ' |')
    for lang in LANGUAGES:
        print(f'{lang}: {len(found[lang])}/38; missing: {", ".join(sorted(expected - found[lang])) or "none"}')
    return '\n'.join(rows) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Update the Markdown coverage table')
    args = parser.parse_args()
    table = audit()
    if args.write:
        (ROOT / 'docs/shakespeare-coverage.md').write_text(table, encoding='utf-8')
